def get_category_catalog() -> List[CategoryDefinition]:
    """Return all ten canonical OWASP GenAI 2026 category definitions in order."""
    return list(_CATALOG)


def get_category_definition(category: str) -> Optional[CategoryDefinition]:
    """
    Resolve a category ID, code, or historical alias to its canonical 2026 definition.
    
    Accepts:
        - "LLM08", "llm08", "LLM08:2026"
        - Historical 2025 aliases: "LLM07:2025", "System Prompt Leakage" -> resolves to LLM08
        - Returns None if unrecognized.
    """
    if not category:
        return None
    cleaned = category.strip()
    upper = cleaned.upper()

    for item in _CATALOG:
        if upper == item.id.upper() or upper == item.code.upper():
            return item
        if cleaned.lower() == item.name.lower():
            return item
        for alias in item.legacy_aliases:
            if upper == alias.upper() or cleaned.lower() == alias.lower():
                return item

    return None

