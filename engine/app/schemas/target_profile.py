"""Target Profile Schema and Evidence Normalization Models."""
from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class FieldEvidence(BaseModel):
    """
    Uniform container for detected capabilities, technologies, and classifications.
    Every profile field carries explicit evidence and a confidence score.
    """
    detected: bool = False
    value: Optional[str] = None
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    evidence: List[str] = Field(default_factory=list)
    source: Literal[
        "passive",
        "probe",
        "classifier",
        "tier2_psutil",
        "tier3_static",
        "corroborated",
        "fallback",
    ] = "fallback"


class TargetProfile(BaseModel):
    """
    Normalized Target Profile generated by the Recon Agent (Step 0a).
    Feeds the deterministic Test Planner (Step 0b).
    """
    target_id: str
    target_url: Optional[str] = None
    site_type: FieldEvidence = Field(default_factory=lambda: FieldEvidence(value="general_assistant"))
    primary_domain: FieldEvidence = Field(default_factory=lambda: FieldEvidence(value="general"))
    has_rag: FieldEvidence = Field(default_factory=FieldEvidence)
    has_vector_db: FieldEvidence = Field(default_factory=FieldEvidence)
    has_tools: FieldEvidence = Field(default_factory=FieldEvidence)
    has_conversation_memory: FieldEvidence = Field(default_factory=FieldEvidence)
    has_streaming: FieldEvidence = Field(default_factory=FieldEvidence)
    renders_html: FieldEvidence = Field(default_factory=FieldEvidence)
    renders_markdown: FieldEvidence = Field(default_factory=FieldEvidence)
    detected_frameworks: List[str] = Field(default_factory=list)
    detected_endpoints: List[str] = Field(default_factory=list)
    raw_signals: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

